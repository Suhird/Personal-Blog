import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DIST_DIR = path.resolve(__dirname, '../dist');
const POSTS_DIR = path.resolve(__dirname, '../src/data/posts');

function extractField(content, field) {
  const regex = new RegExp(`${field}:\\s*"([^"]+)"`);
  const match = content.match(regex);
  return match ? match[1] : '';
}

if (!fs.existsSync(DIST_DIR)) {
  console.error('dist/ does not exist. Run the build first.');
  process.exit(1);
}

const postFiles = fs.readdirSync(POSTS_DIR).filter((file) => file.endsWith('.ts'));

const legacyRules = postFiles.flatMap((file) => {
  const content = fs.readFileSync(path.join(POSTS_DIR, file), 'utf-8');
  const slug = extractField(content, 'slug');
  const category = extractField(content, 'category');
  if (!slug) return [];

  const section = category === 'life' ? 'beyond-code' : 'tech-blog';

  return [
    `/blog/${slug} /${section}/${slug}/ 301`,
    `/blog/${slug}/ /${section}/${slug}/ 301`,
  ];
});

const rules = [
  '# Cloudflare Pages redirects. Generated by scripts/generate-cloudflare-redirects.js.',
  '# Keep exact post redirects before the generic /blog/* fallback.',
  '',
  '/blog /tech-blog/ 301',
  '/blog/ /tech-blog/ 301',
  ...legacyRules,
  '',
  '# Unknown /blog/* paths fall back to the tech index.',
  '/blog/* /tech-blog/:splat 301',
  '',
  '# Static routes are generated by postbuild, so no SPA catch-all is needed.',
  '# Cloudflare will serve dist/404.html for unknown paths.',
  '',
].join('\n');

fs.writeFileSync(path.join(DIST_DIR, '_redirects'), rules);
console.log(`Generated dist/_redirects with ${legacyRules.length / 2} legacy post redirects.`);
